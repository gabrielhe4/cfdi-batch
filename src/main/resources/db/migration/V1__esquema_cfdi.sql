-- Esquema de dominio. Las tablas BATCH_* las crea Spring Batch.

CREATE SEQUENCE comprobante_seq START WITH 1 INCREMENT BY 50;
CREATE SEQUENCE concepto_seq    START WITH 1 INCREMENT BY 50;
CREATE SEQUENCE impuesto_seq    START WITH 1 INCREMENT BY 50;

CREATE TABLE comprobante (
    id                 BIGINT        PRIMARY KEY,
    uuid               VARCHAR(36)   NOT NULL,
    version            VARCHAR(5)    NOT NULL,
    serie              VARCHAR(25),
    folio              VARCHAR(40),
    fecha              TIMESTAMP     NOT NULL,
    tipo_comprobante   VARCHAR(1)    NOT NULL,
    forma_pago         VARCHAR(2),
    metodo_pago        VARCHAR(3),
    moneda             VARCHAR(3)    NOT NULL,
    tipo_cambio        NUMERIC(18,6),
    lugar_expedicion   VARCHAR(5),
    subtotal           NUMERIC(18,6) NOT NULL,
    descuento          NUMERIC(18,6) NOT NULL DEFAULT 0,
    total_traslados    NUMERIC(18,6) NOT NULL DEFAULT 0,
    total_retenidos    NUMERIC(18,6) NOT NULL DEFAULT 0,
    total              NUMERIC(18,6) NOT NULL,
    emisor_rfc         VARCHAR(13)   NOT NULL,
    emisor_nombre      VARCHAR(300),
    emisor_regimen     VARCHAR(3),
    receptor_rfc       VARCHAR(13)   NOT NULL,
    receptor_nombre    VARCHAR(300),
    receptor_uso_cfdi  VARCHAR(4),
    fecha_timbrado     TIMESTAMP     NOT NULL,
    archivo            VARCHAR(255)  NOT NULL,
    job_execution_id   BIGINT        NOT NULL,
    fecha_carga        TIMESTAMP     NOT NULL,
    CONSTRAINT uk_comprobante_uuid UNIQUE (uuid)
);

CREATE INDEX ix_comprobante_emisor_fecha ON comprobante (emisor_rfc, fecha);
CREATE INDEX ix_comprobante_job ON comprobante (job_execution_id);

CREATE TABLE concepto (
    id                BIGINT        PRIMARY KEY,
    comprobante_id    BIGINT        NOT NULL REFERENCES comprobante (id),
    clave_prod_serv   VARCHAR(8),
    no_identificacion VARCHAR(100),
    cantidad          NUMERIC(18,6) NOT NULL,
    clave_unidad      VARCHAR(3),
    descripcion       VARCHAR(1000),
    valor_unitario    NUMERIC(18,6) NOT NULL,
    importe           NUMERIC(18,6) NOT NULL,
    descuento         NUMERIC(18,6) NOT NULL DEFAULT 0,
    objeto_imp        VARCHAR(2)
);

CREATE INDEX ix_concepto_comprobante ON concepto (comprobante_id);

CREATE TABLE impuesto (
    id              BIGINT        PRIMARY KEY,
    comprobante_id  BIGINT        NOT NULL REFERENCES comprobante (id),
    tipo            VARCHAR(10)   NOT NULL,   -- TRASLADO | RETENCION
    impuesto        VARCHAR(3)    NOT NULL,   -- 001 ISR, 002 IVA, 003 IEPS
    tipo_factor     VARCHAR(10),
    tasa_o_cuota    NUMERIC(18,6),
    base            NUMERIC(18,6),
    importe         NUMERIC(18,6) NOT NULL
);

CREATE INDEX ix_impuesto_comprobante ON impuesto (comprobante_id);

CREATE TABLE cfdi_rechazado (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_execution_id  BIGINT        NOT NULL,
    archivo           VARCHAR(255)  NOT NULL,
    uuid              VARCHAR(36),
    motivo            VARCHAR(2000),
    fecha             TIMESTAMP     NOT NULL
);

CREATE INDEX ix_rechazado_job ON cfdi_rechazado (job_execution_id);
